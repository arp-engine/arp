#pragma once

#include "renderer/raster_viewport.h"

// SsrRenderer - WoCC Screen-Space Reflection renderer.
//
// Owns the trace compute pipeline, composite graphics pipeline, persistent
// reflection storage texture, double-buffered descriptor sets, and samplers
// for the two-pass SSR chain:
//   1. Trace (compute, [numthreads(8,8,1)]): per-pixel linear ray march in
//      view space against the scene depth buffer, with binary refinement.
//      Writes reflection color + hit confidence (RGBA16F: RGB = reflected
//      color sampled from SceneColorTexture, A = hit confidence [0,1]) to
//      the persistent SsrReflectionOut storage texture.
//   2. Composite (fragment, fullscreen triangle): reads SsrReflectionInput
//      (the trace result, same physical texture as SsrReflectionOut but
//      bound as a sampled texture) + SceneColorTexture, blends reflection
//      over scene color by hit confidence. Runs in HDR linear space (before
//      tonemap), so reflections contribute physically to the HDR buffer.
//
// The renderer follows the DdgiRenderer pattern: pipelines and descriptor
// sets are created once in create() and held across frames; the FrameGraph
// invokes recordTracePass / recordCompositePass via ExecuteCallback lambdas.
// The reflection texture is persistent (created once, imported each frame
// via importTextureRef) so it survives across frames for temporal reuse.
//
// Resource ownership:
//   - reflectionTexture_: persistent Rgba16Float 2D texture at full render
//     resolution, Storage|Sampled, GpuOnly. The trace pass writes via the
//     Storage view; the composite pass reads via the Sampled view. Imported
//     each frame via importTextureRef.
//   - reflectionStorageView_: Storage view of reflectionTexture_ (trace).
//   - reflectionSampledView_: Sampled view of reflectionTexture_ (composite).
//   - traceSets_ / compositeSets_: double-buffered (2 slots) descriptor sets
//     to avoid fighting an in-flight frame's descriptor writes.
//   - linearSampler_: linear + ClampToEdge for sampling scene color / the
//     reflection texture (reflection UVs may fall outside [0,1] during ray
//     march; clamp prevents border artifacts).
//
// Matrix layout contract (AGENTS.md section 3): this renderer does NOT pass
// any float4x4 in push constants. The inverse view-projection is packed as
// two float4 rows (invViewProjectionY, invViewProjectionW) to reconstruct
// world position from clip-space depth, mirroring post_fx.slang's fog pass.
// This sidesteps the cross-language matrix-layout contract entirely - no
// RowMajor/ColMajor SPV decoration applies to SsrPushConstants.
//
// Capability gate (AGENTS.md fail-closed): SSR requires compute dispatch +
// storage texture binding. On Vulkan both are Native as of Phase 1
// (vulkanNativeFeatures declares them). On Metal both are DiagnosticFailure
// (recordDispatch is a stat-only stub; storage texture binding is stubbed).
// On WebGPU both are runtime-probed (rgba16FloatStorage probe in the
// browser profile). On Null both are Native (reference validator). When the
// gate fails, create() returns {false, diagnostic} and the pipeline falls
// back to WOCC_DISABLE_SSR semantics (bloomColor passes straight to fog).
//
// NOTE: This is Prototype Complete as of Phase 5. Backend Validated on
// Vulkan follows in Phase 8 (RenderDoc capture). Metal/WebGPU remain
// DiagnosticFailure per the four-backend contract.

