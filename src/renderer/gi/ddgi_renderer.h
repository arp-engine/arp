// DDGI push-constants layout is the single source of truth from ddgi.slang;
// the struct is auto-generated by scripts/shader_bindings_codegen.py from
// SPIRV-Reflect on ddgi.spv. Do not hand-edit - regenerate shaders instead.
// The invViewProjection field is row-major (core::inverse produces row-major),
// and the shader declares a DEFAULT float4x4 (no row_major keyword) so SPIR-V
// reads it as RowMajor - matching the C++ row-major data. Per AGENTS.md
// matrix-layout contract, this struct must not declare row_major and the
// shader struct body must contain no // comments.
using DdgiPushConstants = arp::shader::gen::DdgiPushConstants;

inline float ddgiUintBitsAsFloat(std::uint32_t value) noexcept
{
    float result = 0.0f;
    std::memcpy(&result, &value, sizeof(result));
    return result;
}

/// Build the ray-march hierarchy from the exact grid uploaded to DDGI.  A
/// bilinear R32 height texture cannot exceed its source texels, so each base
/// cell aggregates every source texel it overlaps.  This is conservative for
/// arbitrary rectangular TerrainSurface bounds without analytic margins.
inline arp::core::pmr::Vector<std::array<float, 4>> buildDdgiTerrainMinMaxHierarchy(
    const DdgiBakedTerrainGrid& terrain,
    std::pmr::memory_resource* memoryResource = &arp::core::defaultCpuMemoryResource())
{
    const DdgiTerrainMinMaxHierarchyLayout layout;
    arp::core::pmr::Vector<std::array<float, 4>> records(memoryResource);
    if (!terrain.valid())
        return records;
    records.resize(layout.totalRecordCount());
    records[0] = {
        terrain.bounds.minX, terrain.bounds.minZ, terrain.bounds.maxX, terrain.bounds.maxZ};
    records[1] = {ddgiUintBitsAsFloat(terrain.samplesX),
        ddgiUintBitsAsFloat(terrain.samplesZ),
        ddgiUintBitsAsFloat(layout.levelCount),
        ddgiUintBitsAsFloat(layout.totalRecordCount())};
    const auto baseResolution = layout.levelResolution(0u);
    const auto baseOffset = layout.levelOffset(0u);
    for (std::uint32_t z = 0u; z < baseResolution; ++z) {
        const auto sourceZ0 =
            std::min(terrain.samplesZ - 1u, z * (terrain.samplesZ - 1u) / baseResolution);
        const auto sourceZ1 = std::min(terrain.samplesZ - 1u,
            ((z + 1u) * (terrain.samplesZ - 1u) + baseResolution - 1u) / baseResolution);
        for (std::uint32_t x = 0u; x < baseResolution; ++x) {
            const auto sourceX0 =
                std::min(terrain.samplesX - 1u, x * (terrain.samplesX - 1u) / baseResolution);
            const auto sourceX1 = std::min(terrain.samplesX - 1u,
                ((x + 1u) * (terrain.samplesX - 1u) + baseResolution - 1u) / baseResolution);
            float minHeight = std::numeric_limits<float>::max();
            float maxHeight = -std::numeric_limits<float>::max();
            for (std::uint32_t sourceZ = sourceZ0; sourceZ <= sourceZ1; ++sourceZ) {
                for (std::uint32_t sourceX = sourceX0; sourceX <= sourceX1; ++sourceX) {
                    const float value =
                        terrain.heights[static_cast<std::size_t>(sourceZ) * terrain.samplesX
                            + sourceX];
                    minHeight = std::min(minHeight, value);
                    maxHeight = std::max(maxHeight, value);
                }
            }
            records[baseOffset + z * baseResolution + x] = {minHeight, maxHeight, 0.0f, 0.0f};
        }
    }
    for (std::uint32_t level = 1u; level < layout.levelCount; ++level) {
        const auto childResolution = layout.levelResolution(level - 1u);
        const auto resolution = layout.levelResolution(level);
        const auto childOffset = layout.levelOffset(level - 1u);
        const auto offset = layout.levelOffset(level);
        for (std::uint32_t z = 0u; z < resolution; ++z) {
            for (std::uint32_t x = 0u; x < resolution; ++x) {
                float minHeight = std::numeric_limits<float>::max();
                float maxHeight = -std::numeric_limits<float>::max();
                for (std::uint32_t dz = 0u; dz < 2u; ++dz) {
                    for (std::uint32_t dx = 0u; dx < 2u; ++dx) {
                        const auto childX = std::min(childResolution - 1u, x * 2u + dx);
                        const auto childZ = std::min(childResolution - 1u, z * 2u + dz);
                        const auto& child =
                            records[childOffset + childZ * childResolution + childX];
                        minHeight = std::min(minHeight, child[0]);
                        maxHeight = std::max(maxHeight, child[1]);
                    }
                }
                records[offset + z * resolution + x] = {minHeight, maxHeight, 0.0f, 0.0f};
            }
        }
    }
    return records;
}

