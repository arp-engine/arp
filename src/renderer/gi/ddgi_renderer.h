// Phase 4: scene BVH triangle leaf, mirrored 1:1 with the shader struct
// GpuBvhLeaf in ddgi.slang (binding 11, ReadOnlyStorageBuffer). Each leaf carries
// one triangle's vertices + face normal + material index + UVs. Legacy BVHs
// keep world-space vertices; the explicit split static BLAS uses local-space
// vertices transformed through the instance table. The
// BVH builder (src/3d/bvh.cpp buildRecursive) always splits down to one
// triangle per leaf, so the GPU traversal assumes leafCount == 1 and does
// not need a separate leaf-count array.
//
// Layout (96 bytes, std430 via 16-byte alignment per float3 component):
//   float3 v0;         // 12 bytes (aligned 16)
//   float  _pad0;      //  4 bytes
//   float3 v1;         // 12 bytes (aligned 16)
//   float  _pad1;      //  4 bytes
//   float3 v2;         // 12 bytes (aligned 16)
//   float  _pad2;      //  4 bytes
//   float3 normal;     // 12 bytes (aligned 16)
//   uint   materialIdx;//  4 bytes
//   float2 uv0;        //  8 bytes
//   float2 uv1;        //  8 bytes
//   float2 uv2;        //  8 bytes
//   float2 _uvPad;     //  8 bytes (struct alignment)
// In the shader, float3 (vec3) has 16-byte alignment under std430, so each
// (float3, scalar) pair occupies exactly 16 bytes. The C++ side uses float[3]
// (4-byte alignment) with explicit pad fields to match the byte layout
// exactly. Both produce the same 96-byte struct.
struct GpuBvhLeafData {
    float v0[3];
    float pad0;
    float v1[3];
    float pad1;
    float v2[3];
    float pad2;
    float normal[3];
    std::uint32_t materialIdx;
    float uv0[2];
    float uv1[2];
    float uv2[2];
    float uvPad[2];
};

static_assert(sizeof(GpuBvhLeafData) == 96,
    "GpuBvhLeafData must be 96 bytes (matches shader GpuBvhLeaf under std430)");

// Emissive radiance is keyed by the serialized BVH leaf index. Keeping it in
