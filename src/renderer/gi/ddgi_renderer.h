inline DdgiSkyEnvironmentGpu packDdgiSkyEnvironment(const DdgiSkyEnvironmentDesc& source) noexcept
{
    DdgiSkyEnvironmentGpu gpu{};
    for (std::uint32_t i = 0u; i < 3u; ++i) {
        gpu.horizonRadiance[i] = source.horizonRadiance[i];
        gpu.zenithRadiance[i] = source.zenithRadiance[i];
        gpu.sunRadiance[i] = source.sunRadiance[i];
        gpu.sunDirection[i] = source.sunDirection[i];
    }
    gpu.angularParams[0] = source.glowPower;
    gpu.angularParams[1] = source.glowStrength;
    gpu.angularParams[2] = source.corePower;
    gpu.angularParams[3] = source.coreStrength;
    gpu.preExposure[0] = source.preExposure;
    gpu.preExposure[1] = source.horizonPower;
    return gpu;
}

// Phase 3: per-probe relocation state, mirrored 1:1 with the shader struct
// ProbeState in ddgi.slang (binding 9, RWStructuredBuffer). Authored by the
// ProbeRelocate compute pass, read by probe-update + resolve via probeWorldPos.
// Layout: offset.xyz (world-space relocation offset) + status (packed reason
// + flags). The status bit layout matches the shader constants:
//   bits 0-3   = relocation reason (kProbeRelocReason_*)
//   bit  8     = ScrollNewCell flag (forces history reset in update pass)
static_assert(sizeof(float) == 4, "ProbeState assumes 32-bit float");

struct ProbeState {
    float offset[3]{};
    std::uint32_t status = 0u;
    std::int32_t logicalCell[3]{};
    std::uint32_t classification = 0u;
    std::uint32_t age = 0u;
    float confidence = 0.0f;
    std::uint32_t lastUpdateFrame = 0u;
    std::uint32_t lightingRevision = 0u;
    float reserved[4]{};
};

static_assert(sizeof(ProbeState) == 64, "ProbeState must be 64 bytes (matches shader)");

