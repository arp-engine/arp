// Main directional-light CSM contract consumed by probe tracing. Matrices
// use the same row-major/default-float4x4 ABI as the scene receivers. Atlas
// transforms are xy scale + zw offset in normalized texture coordinates.
struct alignas(16) DdgiCsmShadowDesc {
    float lightViewProjection[3][16]{};
    float cascadeSplits[4]{};
    float atlasUvTransforms[3][4]{};
    float shadowParams[4]{}; // x=enabled, y=pcf radius, z=strength, w=resolution
};

static_assert(sizeof(DdgiCsmShadowDesc) == 272u);

inline bool isValidDdgiCsmShadow(const DdgiCsmShadowDesc& shadow) noexcept
{
    for (const auto& matrix : shadow.lightViewProjection) {
        for (const auto value : matrix) {
            if (!std::isfinite(value))
                return false;
        }
    }
    for (const auto value : shadow.cascadeSplits) {
        if (!std::isfinite(value))
            return false;
    }
    for (const auto& transform : shadow.atlasUvTransforms) {
        for (const auto value : transform) {
            if (!std::isfinite(value))
                return false;
        }
    }
    for (const auto value : shadow.shadowParams) {
        if (!std::isfinite(value))
            return false;
    }
    if (shadow.shadowParams[0] < 0.0f || shadow.shadowParams[0] > 1.0f
        || shadow.shadowParams[1] < 0.0f || shadow.shadowParams[2] < 0.0f
        || shadow.shadowParams[2] > 1.0f || shadow.shadowParams[3] < 0.0f) {
        return false;
    }
    if (shadow.shadowParams[0] > 0.0f && shadow.shadowParams[3] <= 0.0f) {
        return false;
    }
    return shadow.cascadeSplits[0] >= 0.0f && shadow.cascadeSplits[1] >= shadow.cascadeSplits[0]
        && shadow.cascadeSplits[2] >= shadow.cascadeSplits[1]
        && shadow.cascadeSplits[3] >= shadow.cascadeSplits[2];
}

