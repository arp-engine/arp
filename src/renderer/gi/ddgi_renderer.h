#pragma once

// DdgiRenderer - engine dynamic diffuse global illumination renderer.
//
// Owns the compute pipelines, descriptor sets, ping-pong probe-irradiance
// textures, terrain UBO, and samplers for the six-dispatch DDGI chain:
//   1. ProbeRelocate: move probes clear of the baked terrain surface.
//   2. ProbeTrace: trace bounded cosine-weighted rays and write a transient
//      (radiance, distance) record per ray.
//   3. BlendIrradiance: consume the transient and write the irradiance atlas.
//   4. BlendDistance: consume the transient and commit depth moments/state.
//   5. BorderUpdate: copy the one-texel irradiance and distance atlas borders
//      after the interior blend, with its own hazard and timestamp scope.
//   6. Resolve: per half-resolution pixel, reconstruct world position from
//      scene depth + inverse view-projection, trilinear-blend the 8 surrounding
//      probes' octahedral irradiance (keyed by the reconstructed surface normal),
//      apply Chebyshev ambient occlusion, and write to the half-res GI output.
//
// The renderer follows the SsaoRenderer pattern: pipelines and descriptor sets
// are created once in create() and held across frames; the FrameGraph invokes
// recordProbeTracePass / recordProbeBlend*Pass / recordResolvePass via
// ExecuteCallback lambdas. The
// ping-pong probe textures are persistent (created once, imported each frame
// via importTextureRef) to support temporal hysteresis.
//
// Resource ownership:
//   - probeIrradianceA_ / probeIrradianceB_: persistent Rgba16Float 2D textures
//     (countX*8 x countY*countZ*8), Storage|Sampled, GpuOnly. Imported each frame.
//   - giOutputA_ / giOutputB_: persistent Rgba16Float 2D textures at half
//     render resolution, Storage|Sampled, GpuOnly. The resolve pass writes
//     the current frame's GI into giOutputWrite, and the PBR scene shader
//     samples giOutputRead (the previous frame's result) - a 1-frame lag
//     breaks the scene-pass-needs-depth / resolve-needs-depth dependency
//     cycle without a persistent depth history. Imported each frame.
//   - terrainPayload_: persistent sampled R32 height texture copied from the
//     immutable baked TerrainSurface grid.
//   - probeUpdateSets_ / resolveSets_: double-buffered (2 slots) descriptor sets
//     to avoid fighting an in-flight frame's descriptor writes.
//   - cachedDepthView_: depth-aspect TextureView for the scene depth, rebuilt
//     only when the source depth texture id changes (mirrors SSAO's input cache).

