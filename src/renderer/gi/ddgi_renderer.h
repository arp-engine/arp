    void ensureCsmShadowReadable(render_graph::RenderContext& context)
    {
        if (!csmShadowTexture_)
            throw core::DiagnosticError("DDGI-CSM-SHADOW-MISSING");
        if (!sceneMaterialBuffer_)
            throw core::DiagnosticError("DDGI-MATERIAL-BUFFER-MISSING");
        const auto materialBefore = sceneMaterialBuffer_->state();
        if (materialBefore != rhi::ResourceState::ShaderRead)
            core::requireSuccessfulResult(
                context.commands().transition(
                    *sceneMaterialBuffer_, materialBefore, rhi::ResourceState::ShaderRead),
                "DDGI-MATERIAL-TRANSITION-FAILED");
        const auto before = csmShadowTexture_->state();
        if (before == rhi::ResourceState::ShaderRead)
            return;
        core::requireSuccessfulResult(
            context.commands().transition(
                *csmShadowTexture_, before, rhi::ResourceState::ShaderRead),
            "DDGI-CSM-SHADOW-TRANSITION-FAILED");
    }

    static std::pmr::string replaceExt(const std::pmr::string& path, const char* ext)
    {
        const auto dot = path.find_last_of('.');
        const auto base = (dot != std::pmr::string::npos) ? path.substr(0, dot) : path;
        return base + ext;
    }

    enum class LocalLightUpdatePhase { ValidateOnly, Upload };

    RendererResult updateLocalLightInfluences(
        const DdgiPushConstants& pc, LocalLightUpdatePhase phase = LocalLightUpdatePhase::Upload)
    {
        if (!localLightBuffer_ || !probeLocalLightInfluenceBuffer_) {
            return {false, "DDGI local-light buffers are not initialized"};
        }
        std::array<float, 3> origin{};
        std::array<float, 3> spacing{};
        for (std::uint32_t axis = 0u; axis < 3u; ++axis) {
            origin[axis] = pc.probeGridOriginHysteresis[axis];
            spacing[axis] = pc.probeGridSpacingStrength[axis];
            if (!std::isfinite(origin[axis]) || !std::isfinite(spacing[axis])
                || spacing[axis] <= 0.0f) {
                return {false, "DDGI local-light influence requires finite positive grid spacing"};
            }
        }
        const auto ringOffset = std::array<std::int32_t, 3>{
            static_cast<std::int32_t>(std::lround(pc.scrollOffsetFrame[0])),
            static_cast<std::int32_t>(std::lround(pc.scrollOffsetFrame[1])),
            static_cast<std::int32_t>(std::lround(pc.scrollOffsetFrame[2])),
        };
        if (localLightInfluenceCacheValid_ && localLightUploadRevision_ == localLightsRevision_
            && (localLights_.empty()
                || (origin == localLightGridOrigin_ && spacing == localLightGridSpacing_
                    && ringOffset == localLightRingOffset_))) {
            return {true, ""};
        }
        if (!sharedInputsReady())
            return {false, "DDGI-SHARED-LIGHT-INPUT-NOT-READY"};
        if (phase == LocalLightUpdatePhase::ValidateOnly)
            return {true, ""};

        arp::core::pmr::Vector<DdgiLocalLightGpu> gpuLights(
            kDdgiMaxLocalLights, DdgiLocalLightGpu{}, &arp::core::defaultCpuMemoryResource());
        for (std::uint32_t index = 0u; index < localLights_.size(); ++index) {
            const auto& source = localLights_[index];
            auto& destination = gpuLights[index];
            destination.positionAndRange[0] = source.position[0];
            destination.positionAndRange[1] = source.position[1];
            destination.positionAndRange[2] = source.position[2];
            destination.positionAndRange[3] = source.range;
            destination.radianceAndIntensity[0] = source.radiance[0];
            destination.radianceAndIntensity[1] = source.radiance[1];
            destination.radianceAndIntensity[2] = source.radiance[2];
            destination.radianceAndIntensity[3] = source.intensity;
        }

        const auto totalProbeCount =
            static_cast<std::size_t>(probeCount_[0]) * probeCount_[1] * probeCount_[2];
        arp::core::pmr::Vector<std::uint32_t> influences(
            totalProbeCount * kDdgiMaxLocalLightsPerProbe,
            kDdgiInvalidLocalLightIndex,
            &arp::core::defaultCpuMemoryResource());
        const auto positiveModulo = [](std::int32_t value, std::int32_t divisor) {
            return (value % divisor + divisor) % divisor;
        };
        for (std::uint32_t z = 0u; z < probeCount_[2]; ++z) {
            for (std::uint32_t y = 0u; y < probeCount_[1]; ++y) {
                for (std::uint32_t x = 0u; x < probeCount_[0]; ++x) {
                    std::array<float, kDdgiMaxLocalLightsPerProbe> bestDistance;
                    std::array<std::uint32_t, kDdgiMaxLocalLightsPerProbe> bestIndex;
                    bestDistance.fill(std::numeric_limits<float>::max());
                    bestIndex.fill(kDdgiInvalidLocalLightIndex);
                    const float px = origin[0] + static_cast<float>(x) * spacing[0];
                    const float py = origin[1] + static_cast<float>(y) * spacing[1];
                    const float pz = origin[2] + static_cast<float>(z) * spacing[2];
                    for (std::uint32_t lightIndex = 0u; lightIndex < localLights_.size();
                        ++lightIndex) {
                        const auto& light = localLights_[lightIndex];
                        const float dx = light.position[0] - px;
                        const float dy = light.position[1] - py;
                        const float dz = light.position[2] - pz;
                        const float distanceSquared = dx * dx + dy * dy + dz * dz;
                        if (distanceSquared > light.range * light.range)
                            continue;
                        std::uint32_t insertion = kDdgiMaxLocalLightsPerProbe;
                        for (std::uint32_t slot = 0u; slot < kDdgiMaxLocalLightsPerProbe; ++slot) {
                            if (distanceSquared < bestDistance[slot]) {
                                insertion = slot;
                                break;
                            }
                        }
                        if (insertion == kDdgiMaxLocalLightsPerProbe)
                            continue;
                        for (std::uint32_t slot = kDdgiMaxLocalLightsPerProbe - 1u;
                            slot > insertion;
                            --slot) {
                            bestDistance[slot] = bestDistance[slot - 1u];
                            bestIndex[slot] = bestIndex[slot - 1u];
                        }
                        bestDistance[insertion] = distanceSquared;
                        bestIndex[insertion] = lightIndex;
                    }
                    const auto physicalX = static_cast<std::uint32_t>(
                        positiveModulo(static_cast<std::int32_t>(x) + ringOffset[0],
                            static_cast<std::int32_t>(probeCount_[0])));
                    const auto physicalY = static_cast<std::uint32_t>(
                        positiveModulo(static_cast<std::int32_t>(y) + ringOffset[1],
                            static_cast<std::int32_t>(probeCount_[1])));
                    const auto physicalZ = static_cast<std::uint32_t>(
                        positiveModulo(static_cast<std::int32_t>(z) + ringOffset[2],
                            static_cast<std::int32_t>(probeCount_[2])));
                    const auto physicalIndex = physicalX + physicalY * probeCount_[0]
                        + physicalZ * probeCount_[0] * probeCount_[1];
                    for (std::uint32_t slot = 0u; slot < kDdgiMaxLocalLightsPerProbe; ++slot) {
                        influences[physicalIndex * kDdgiMaxLocalLightsPerProbe + slot] =
                            bestIndex[slot];
                    }
                }
            }
        }
        // A failed upload may already have changed physical bytes. Returning
        // to the previous grid key must rewrite, not reuse the old cache claim.
        localLightInfluenceCacheValid_ = false;
        const auto lightsWritten = device_.writeBuffer(
            *localLightBuffer_, gpuLights.data(), gpuLights.size() * sizeof(DdgiLocalLightGpu));
        if (!lightsWritten.success) {
            return {false, "DDGI local-light upload failed: " + lightsWritten.diagnostics};
        }
        const auto influencesWritten = device_.writeBuffer(*probeLocalLightInfluenceBuffer_,
            influences.data(),
            influences.size() * sizeof(std::uint32_t));
        if (!influencesWritten.success) {
            return {false,
                "DDGI local-light influence upload failed: " + influencesWritten.diagnostics};
        }
        localLightGridOrigin_ = origin;
        localLightGridSpacing_ = spacing;
        localLightRingOffset_ = ringOffset;
        localLightUploadRevision_ = localLightsRevision_;
        localLightInfluenceCacheValid_ = true;
        return {true, ""};
    }

    bool matchesPreparedHistory(render_graph::PassSubmissionToken token) const noexcept
    {
        return recordingReady_ && probeScheduler_ && token.ownerId != 0u && token.generation != 0u
            && token.ownerId == preparedSchedule_.ownerId
            && token.generation == preparedSchedule_.generation;
    }

    bool matchesPreparedInput(render_graph::PassSubmissionToken token) const noexcept
    {
        return token.ownerId != 0u && token.generation != 0u
            && token.ownerId == preparedInputToken_.ownerId
            && token.generation == preparedInputToken_.generation;
    }

    bool canAcceptPreparedInput(render_graph::PassSubmissionToken token,
        const std::shared_ptr<const rhi::GpuFence>& completion) const noexcept
    {
        if (!recordingReady_ || !matchesPreparedInput(token) || !completion)
            return false;
        const auto& lease = inputLeases_[preparedInputSlot_];
        return preparedInputAccepted_ ? lease.matches(completion) : lease.canRetain(completion);
    }

