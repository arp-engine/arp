    // The first resolve samples the initial probe history. Do not expose its
    // GI output: only the following resolve has a fully authored probe atlas.
    // This also makes resize/device-recovery safe without sampling undefined
    // persistent texture contents.
    bool hasValidGiHistory() const { return completedResolveCount_ >= 1u; }

    render_graph::PassSubmissionToken preparedHistoryToken() const noexcept
    {
        return {preparedSchedule_.ownerId, preparedSchedule_.generation};
    }

    bool inputSlotReady(std::uint32_t frameIndex) const
    {
        return inputLeases_[frameIndex % kDdgiDescriptorSetSlots].ready();
    }

    // Shared input bytes may be mutated only after every accepted slot reader
    // completes. This is bounded polling, never a CPU/GPU wait.
    bool sharedInputsReady() const
    {
        for (const auto& lease : inputLeases_)
            if (!lease.ready())
                return false;
        return true;
    }

    bool isPreparedInput(render_graph::PassSubmissionToken token) const noexcept
    {
        return recordingReady_ && !preparedInputAccepted_ && matchesPreparedInput(token)
            && inputLeases_[preparedInputSlot_].ready();
    }

    bool acceptPreparedInput(render_graph::PassSubmissionToken token,
        const std::shared_ptr<const rhi::GpuFence>& completion) noexcept
    {
        if (!canAcceptPreparedInput(token, completion))
            return false;
        if (!inputLeases_[preparedInputSlot_].retain(completion))
            return false;
        preparedInputAccepted_ = true;
        return true;
    }

    bool isPreparedHistory(render_graph::PassSubmissionToken token) const noexcept
    {
        return matchesPreparedHistory(token) && isPreparedInput(token);
    }

    // Called only at queue acceptance with the graph's exact copied identity.
    bool acceptPreparedHistory(render_graph::PassSubmissionToken token,
        const std::shared_ptr<const rhi::GpuFence>& completion) noexcept
    {
        if (!matchesPreparedHistory(token) || !canAcceptPreparedInput(token, completion)
            || !probeScheduler_->commit(preparedSchedule_))
            return false;
        const auto retained = acceptPreparedInput(token, completion);
        assert(retained); // Prevalidated; preparation/acceptance are externally serialized.
        acceptedScheduleGeneration_ = preparedSchedule_.generation;
        preparedSchedule_ = {};
        currentReadIndex_ = 1 - currentReadIndex_;
        if (completedResolveCount_ < 2u) {
            ++completedResolveCount_;
        }
        return true;
    }

    // Phase 4: whether the backend supports scene geometry ray query. The
    // pipeline checks this before collecting triangle data for updateSceneBvh
    // (collecting is wasted work when the gate failed). When false, the
    // shader's sceneBvhParams.x stays 0 and the update pass uses the
    // analytic-terrain fallback (marchTerrain).
    bool sceneGeometryRayQuerySupported() const { return sceneGeometryRayQuerySupported_; }

    /// Bind one semantic material category used by the DDGI BVH. Resource
    /// ownership remains with the application render pipeline; DDGI stores only RHI
    /// identities and re-writes them into each frame-slot descriptor set.
    bool validSceneMaterial(const DdgiSceneBvhTriangle& triangle) const noexcept
    {
        const auto material = triangle.materialIdx;
        if ((material & 0xc0000000u) != kDdgiSceneMaterialFlag)
            return true;
        if ((material & 0x3fffffffu) >= sceneMaterialCount_)
            return false;
        for (const auto* uv : {triangle.uv0, triangle.uv1, triangle.uv2})
            if (!std::isfinite(uv[0]) || !std::isfinite(uv[1]))
                return false;
        return true;
    }

    // Initialization-only upload: existing scene records cannot outlive their table.
    RendererResult setSceneMaterials(arp::core::ArrayView<std::uint32_t> words)
    {
        if (hasValidGiHistory())
            return {false, "DDGI-MATERIAL-UPLOAD-REQUIRES-IDLE-RESET"};
        if (!DdgiSceneMaterials::valid(words))
            return {false, "DDGI-MATERIAL-TABLE-INVALID"};
        const auto limit = device_.capabilities().computeResources.maxStorageBufferBindingSizeBytes;
        if (limit == 0u || words.size_bytes() > limit)
            return {false, "DDGI-MATERIAL-STORAGE-LIMIT"};
        auto candidate = device_.createBuffer({"DdgiSceneMaterials",
            words.size_bytes(),
            rhi::ResourceUsage::StorageBuffer | rhi::ResourceUsage::CopyDst,
            rhi::MemoryUsage::CpuToGpu,
            rhi::ResourceState::Undefined});
        if (!candidate)
            return {false, "DDGI-MATERIAL-BUFFER-CREATE-FAILED"};
        const auto written = device_.writeBuffer(*candidate, words.data(), words.size_bytes());
        if (!written.success)
            return {false, written.diagnostics};
        sceneMaterialBuffer_ = std::move(candidate);
        sceneMaterialCount_ = words[0];
        return {true, ""};
    }

    void setMaterialAlbedo(const std::uint32_t category,
        const rhi::GpuTextureView& view,
        const rhi::GpuSampler& sampler)
    {
        if (category >= kMaterialCategoryCount)
            return;
        materialAlbedoViewIds_[category] = view.id();
        materialAlbedoSamplerId_ = sampler.id();
    }

    // Phase 4: rebuild + upload the scene BVH from the pipeline-collected
    // triangle list. Called once per frame from composeGraph BEFORE the
    // ProbeRelocate / ProbeUpdate / Resolve passes are recorded. Builds the
    // BVH on the CPU (arp::scene3d::Bvh, median-split, one leaf per
    // triangle), serializes to the GPU layout, and uploads both SSBOs. The
    // returned struct carries the triangle/node counts the pipeline must
    // write into DdgiPushConstants::sceneBvhParams so the shader knows
    // whether to trace against the BVH or fall back to marchTerrain.
    //
    // When input.triangleCount == 0 the BVH is cleared (the shader falls
    // back to marchTerrain for this frame). When the triangle count exceeds
    // the current SSBO capacity, the buffers are recreated (orphaning the
    // old GPU memory; the previous frame's in-flight read may stall, but
    // this is rare and preferable to silent truncation).
    struct SceneBvhUpdateResult {
        bool success = true;
        core::pmr::String diagnostic;
        std::uint32_t triangleCount = 0;  // Total leaves, for telemetry.
        std::uint32_t nodeCount = 0;      // Total nodes, for telemetry.
        std::uint32_t proxyAabbCount = 0; // Proxy AABB telemetry, not a tree count.
        std::uint32_t staticTriangleCount = 0;
        std::uint32_t dynamicProxyCount = 0;
        std::uint32_t staticNodeCount = 0;
        std::uint32_t dynamicNodeCount = 0;
        std::uint32_t instanceCount = 0;
        bool rebuilt = false;
        bool refitted = false;
        bool reused = false;
        float buildMilliseconds = 0.0f;
        float refitMilliseconds = 0.0f;
        float uploadMilliseconds = 0.0f;
        std::uint64_t uploadBytes = 0u;
        std::uint32_t changedNodeCount = 0u;
        std::uint32_t changedLeafCount = 0u;
        std::uint32_t uploadRangeCount = 0u;
        std::uint64_t firstChangedPrimitiveId = 0u;
        bool fullUpload = false;

        std::array<float, 4> shaderParameters() const noexcept
        {
            return {static_cast<float>(staticTriangleCount),
                static_cast<float>(staticNodeCount),
                static_cast<float>(dynamicProxyCount),
                static_cast<float>(dynamicNodeCount)};
        }
    };

    SceneBvhUpdateResult updateSceneBvh(const DdgiSceneBvhInput& input)
    {
        SceneBvhUpdateResult result;
        if (!sceneGeometryRayQuerySupported_) {
            return {false, "DDGI-SCENE-GEOMETRY-QUERY-UNAVAILABLE"};
        }
        if ((input.triangleCount != 0u && !input.triangles)
            || (input.staticTriangleCount != 0u && !input.staticTriangles)
            || (input.dynamicTriangleCount != 0u && !input.dynamicTriangles)
            || (input.instanceCount != 0u && !input.instances))
            return {false, "DDGI-BVH-NULL-INPUT"};
        if (input.instanceCount > kMaximumSceneBvhInstances)
            return {false, "DDGI-BVH-INSTANCE-OVERFLOW"};
        if (input.staticTriangleCount != 0u || input.dynamicTriangleCount != 0u
            || input.staticTriangles != nullptr || input.dynamicTriangles != nullptr) {
            return updateSceneBvhSplit(input);
        }
        if (input.triangleCount == 0u || input.triangles == nullptr) {
            if (sceneBvhUploadValid_ && sceneBvhStorageMode_ == SceneBvhStorageMode::Empty)
                return result;
            if (!sharedInputsReady())
                return {false, "DDGI-SHARED-BVH-INPUT-NOT-READY"};
            invalidatePreparedBvhInput();
            cachedSceneGeometryRevision_ = 0u;
            cachedStaticGeometryRevision_ = 0u;
            cachedDynamicGeometryRevision_ = 0u;
            cachedStaticTransformRevision_ = 0u;
            cachedSceneBvhResult_ = {};
            sceneBvh_.clear();
            cachedGpuBvhNodes_.clear();
            cachedGpuBvhLeaves_.clear();
            cachedGpuBvhEmissive_.clear();
            cachedGpuDynamicBvhNodes_.clear();
            cachedGpuDynamicBvhLeaves_.clear();
            cachedGpuDynamicBvhEmissive_.clear();
            staticSceneBvh_.clear();
            dynamicSceneTlas_.clear();
            telemetry_.accelerationBuildMilliseconds = 0.0f;
            telemetry_.accelerationRefitMilliseconds = 0.0f;
            telemetry_.accelerationUploadMilliseconds = 0.0f;
            telemetry_.accelerationUploadBytes = 0u;
            telemetry_.accelerationChangedNodeCount = 0u;
            telemetry_.accelerationChangedLeafCount = 0u;
            telemetry_.accelerationUploadRangeCount = 0u;
            telemetry_.accelerationRebuilt = false;
            telemetry_.accelerationRefitted = false;
            telemetry_.accelerationReused = false;
            sceneBvhUploadValid_ = true;
            sceneBvhStorageMode_ = SceneBvhStorageMode::Empty;
            return result; // no geometry this frame; shader uses marchTerrain
        }
        const auto staticRevision = input.staticGeometryRevision != 0u
            ? input.staticGeometryRevision
            : static_cast<std::uint32_t>(input.geometryRevision >> 32u);
        const auto dynamicRevision = input.dynamicGeometryRevision != 0u
            ? input.dynamicGeometryRevision
            : static_cast<std::uint32_t>(input.geometryRevision);
        const auto staticTransformRevision = input.staticTransformRevision;
        const bool recoverStorage =
            !sceneBvhUploadValid_ || sceneBvhStorageMode_ != SceneBvhStorageMode::Flat;
        const auto accelerationUpdate = planDdgiAccelerationUpdate({
            input.triangleCount,
            static_cast<std::uint32_t>(sceneBvh_.leafCount()),
            staticRevision,
            dynamicRevision,
            cachedStaticGeometryRevision_,
            cachedDynamicGeometryRevision_,
            !recoverStorage && sceneBvh_.nodeCount() != 0u,
            staticTransformRevision,
            cachedStaticTransformRevision_,
        });
        if (accelerationUpdate == DdgiAccelerationUpdateKind::Reuse) {
            // Revision identity is the scene extraction contract.  Once the
            // cached tree matches both revisions, do not touch the caller's
            // triangle array: no validation, bounds collection, hashing,
            // serialization, or upload is needed on this hot path.
            result = cachedSceneBvhResult_;
            result.rebuilt = false;
            result.refitted = false;
            result.reused = true;
            result.buildMilliseconds = 0.0f;
            result.refitMilliseconds = 0.0f;
            result.uploadMilliseconds = 0.0f;
            result.uploadBytes = 0u;
            result.changedNodeCount = 0u;
            result.changedLeafCount = 0u;
            result.uploadRangeCount = 0u;
            result.fullUpload = false;
            telemetry_.accelerationBuildMilliseconds = 0.0f;
            telemetry_.accelerationRefitMilliseconds = 0.0f;
            telemetry_.accelerationUploadMilliseconds = 0.0f;
            telemetry_.accelerationUploadBytes = 0u;
            telemetry_.accelerationChangedNodeCount = 0u;
            telemetry_.accelerationChangedLeafCount = 0u;
            telemetry_.accelerationUploadRangeCount = 0u;
            telemetry_.accelerationRebuilt = false;
            telemetry_.accelerationRefitted = false;
            telemetry_.accelerationReused = true;
            return result;
        }

        if (!sharedInputsReady())
            return {false, "DDGI-SHARED-BVH-INPUT-NOT-READY"};
        for (std::uint32_t index = 0u; index < input.triangleCount; ++index) {
            if (!validSceneMaterial(input.triangles[index]))
                return {false, "DDGI-SCENE-MATERIAL-INVALID"};
            const auto& emissive = input.triangles[index].emissiveRadiance;
            if (!isValidDdgiEmissiveRadiance(emissive)) {
                result.success = false;
                result.diagnostic = "DDGI-EMISSIVE-RADIANCE-INVALID";
                return result;
            }
        }

        invalidatePreparedBvhInput();
        // Build or refit the BVH on the CPU. Static topology changes rebuild;
        // dynamic-only changes preserve leaf ordering and refit node bounds.
        const auto buildStart = std::chrono::steady_clock::now();
        arp::core::pmr::Vector<arp::scene3d::Aabb> boundsByHandle(
            &arp::core::defaultCpuMemoryResource());
        boundsByHandle.resize(input.triangleCount);
        std::uint32_t proxyCount = 0u;
        for (std::uint32_t i = 0u; i < input.triangleCount; ++i) {
            const auto& tri = input.triangles[i];
            arp::scene3d::Aabb bounds;
            if (tri.materialIdx >= 0x80000000u) {
                // Proxy AABB: v0 = min, v1 = max. The degenerate v2 is
                // ignored - the leaf bound is the AABB itself.
                bounds.min.x = tri.v0[0];
                bounds.min.y = tri.v0[1];
                bounds.min.z = tri.v0[2];
                bounds.max.x = tri.v1[0];
                bounds.max.y = tri.v1[1];
                bounds.max.z = tri.v1[2];
                ++proxyCount;
            } else {
                // Real triangle: compute bounds from v0/v1/v2.
                bounds.min.x = std::min(std::min(tri.v0[0], tri.v1[0]), tri.v2[0]);
                bounds.min.y = std::min(std::min(tri.v0[1], tri.v1[1]), tri.v2[1]);
                bounds.min.z = std::min(std::min(tri.v0[2], tri.v1[2]), tri.v2[2]);
                bounds.max.x = std::max(std::max(tri.v0[0], tri.v1[0]), tri.v2[0]);
                bounds.max.y = std::max(std::max(tri.v0[1], tri.v1[1]), tri.v2[1]);
                bounds.max.z = std::max(std::max(tri.v0[2], tri.v1[2]), tri.v2[2]);
            }
            boundsByHandle[i] = bounds;
        }
        const bool topologyCanRefit = accelerationUpdate == DdgiAccelerationUpdateKind::Refit
            || accelerationUpdate == DdgiAccelerationUpdateKind::RefitStaticInstances;
        if (topologyCanRefit) {
            result.refitted = sceneBvh_.refit(boundsByHandle.data(), boundsByHandle.size());
            result.refitMilliseconds = std::chrono::duration<float, std::milli>(
                std::chrono::steady_clock::now() - buildStart)
                                           .count();
        }
        if (!result.refitted) {
            sceneBvh_.clear();
            for (std::uint32_t i = 0u; i < input.triangleCount; ++i) {
                const auto type = input.triangles[i].materialIdx >= 0x80000000u ? 1u : 0u;
                sceneBvh_.insert(boundsByHandle[i], i, type);
            }
            sceneBvh_.build();
            result.buildMilliseconds = std::chrono::duration<float, std::milli>(
                std::chrono::steady_clock::now() - buildStart)
                                           .count();
        }
        const std::size_t nodeCount = sceneBvh_.nodeCount();
        const std::size_t leafCount = sceneBvh_.leafCount();
        if (nodeCount == 0u || leafCount == 0u) {
            return {false, "DDGI-BVH-BUILD-EMPTY"};
        }

        // Grow SSBOs if capacity is insufficient. The previous buffer is
        // released (orphaning GPU memory); a new one is allocated and the
        // old descriptor writes are stale but harmless (the next pass
        // recording re-writes all active bindings, including 10-22).
        bool nodeBufferRecreated = false;
        bool leafBufferRecreated = false;
        if (nodeCount > sceneBvhNodeCapacity_) {
            sceneBvhNodesBuffer_.reset();
            sceneBvhNodeCapacity_ = static_cast<std::uint32_t>(nodeCount);
            sceneBvhNodesBuffer_ = device_.createBuffer({
                "DdgiSceneBvhNodes",
                sceneBvhNodeCapacity_ * sizeof(GpuBvhNodeData),
                rhi::ResourceUsage::StorageBuffer | rhi::ResourceUsage::CopyDst,
                rhi::MemoryUsage::CpuToGpu,
                rhi::ResourceState::Undefined,
            });
            if (!sceneBvhNodesBuffer_) {
                sceneBvhNodeCapacity_ = 0u;
                return {false, "DDGI-BVH-NODE-ALLOCATION-FAILED"};
            }
            nodeBufferRecreated = true;
            cachedGpuBvhNodes_.clear();
        }
        if (leafCount > sceneBvhLeafCapacity_) {
            sceneBvhLeavesBuffer_.reset();
            sceneBvhEmissiveBuffer_.reset();
            sceneBvhLeafCapacity_ = static_cast<std::uint32_t>(leafCount);
            sceneBvhLeavesBuffer_ = device_.createBuffer({
                "DdgiSceneBvhLeaves",
                sceneBvhLeafCapacity_ * sizeof(GpuBvhLeafData),
                rhi::ResourceUsage::StorageBuffer | rhi::ResourceUsage::CopyDst,
                rhi::MemoryUsage::CpuToGpu,
                rhi::ResourceState::Undefined,
            });
            sceneBvhEmissiveBuffer_ = device_.createBuffer({
                "DdgiSceneBvhEmissive",
                sceneBvhLeafCapacity_ * sizeof(GpuBvhEmissiveData),
                rhi::ResourceUsage::StorageBuffer | rhi::ResourceUsage::CopyDst,
                rhi::MemoryUsage::CpuToGpu,
                rhi::ResourceState::Undefined,
            });
            if (!sceneBvhLeavesBuffer_ || !sceneBvhEmissiveBuffer_) {
                sceneBvhLeafCapacity_ = 0u;
                return {false, "DDGI-BVH-LEAF-ALLOCATION-FAILED"};
            }
            leafBufferRecreated = true;
            cachedGpuBvhLeaves_.clear();
            cachedGpuBvhEmissive_.clear();
        }

        // Serialize nodes. The Bvh library returns GpuBvhNodeData in its own
        // layout (32B, same as ours); we reinterpret_cast since the structs
        // are layout-compatible (both are 3 floats + uint + 3 floats + uint
        // with no padding differences under std430 / default C++ alignment).
        const auto uploadStart = std::chrono::steady_clock::now();
        const auto serializedGpuNodes = sceneBvh_.serializeForGpu();
        static_assert(sizeof(arp::scene3d::Bvh::GpuBvhNodeData) == sizeof(GpuBvhNodeData),
            "Bvh::GpuBvhNodeData and local GpuBvhNodeData must match");
        const bool forceFullNodeUpload = !result.refitted || nodeBufferRecreated;
        const auto nodeDiff = arp::core::buildContiguousDiffRanges(serializedGpuNodes.data(),
            serializedGpuNodes.size(),
            forceFullNodeUpload || cachedGpuBvhNodes_.empty() ? nullptr : cachedGpuBvhNodes_.data(),
            forceFullNodeUpload ? 0u : cachedGpuBvhNodes_.size(),
            kMaximumBvhUploadRanges,
            bvhUploadRanges_);
        result.changedNodeCount = static_cast<std::uint32_t>(nodeDiff.changedElementCount);
        result.fullUpload = nodeDiff.fullRangeFallback;
        for (const auto& range : bvhUploadRanges_) {
            const auto sizeBytes = range.elementCount * sizeof(GpuBvhNodeData);
            const auto offsetBytes = range.firstElement * sizeof(GpuBvhNodeData);
            const auto nodesWritten = device_.writeBuffer(*sceneBvhNodesBuffer_,
                serializedGpuNodes.data() + range.firstElement,
                sizeBytes,
                offsetBytes);
            if (!nodesWritten.success) {
                return {false, "DDGI-BVH-NODE-UPLOAD-FAILED: " + nodesWritten.diagnostics};
            }
            result.uploadBytes += sizeBytes;
            ++result.uploadRangeCount;
        }

        // Serialize leaves. bvh.leaves() is reordered by the build; each
        // leaf's .handle encodes the original triangle index from insert().
        // We look up the original triangle and pack its v0/v1/v2 + face
        // normal + materialIdx into the GPU leaf layout. For proxy AABB
        // leaves (materialIdx >= 0x80000000), v0=min and v1=max are stored
        // directly; the shader detects the marker and uses rayAabbIntersect
        // with (v0, v1) as the AABB min/max instead of rayTriangleIntersect.
        arp::core::pmr::Vector<GpuBvhLeafData> gpuLeaves(&arp::core::defaultCpuMemoryResource());
        gpuLeaves.resize(leafCount);
        arp::core::pmr::Vector<GpuBvhEmissiveData> gpuEmissive(
            &arp::core::defaultCpuMemoryResource());
        gpuEmissive.resize(leafCount);
        const auto& leaves = sceneBvh_.leaves();
        for (std::size_t i = 0u; i < leafCount; ++i) {
            const std::uint32_t triIdx = leaves[i].handle;
            const auto& tri = input.triangles[triIdx];
            GpuBvhLeafData& out = gpuLeaves[i];
            GpuBvhEmissiveData& emissiveOut = gpuEmissive[i];
            out = GpuBvhLeafData{};
            emissiveOut = GpuBvhEmissiveData{};
            emissiveOut.radiance[0] = tri.emissiveRadiance[0];
            emissiveOut.radiance[1] = tri.emissiveRadiance[1];
            emissiveOut.radiance[2] = tri.emissiveRadiance[2];
            if (tri.materialIdx >= 0x80000000u) {
                // Proxy AABB: v0 = min, v1 = max, v2 = v0 (degenerate).
                // The shader computes the hit normal from the dominant
                // axis of (hitPoint - center), so the stored normal is
                // just a placeholder.
                out.v0[0] = tri.v0[0];
                out.v0[1] = tri.v0[1];
                out.v0[2] = tri.v0[2];
                out.v1[0] = tri.v1[0];
                out.v1[1] = tri.v1[1];
                out.v1[2] = tri.v1[2];
                out.v2[0] = tri.v0[0];
                out.v2[1] = tri.v0[1];
                out.v2[2] = tri.v0[2];
                out.normal[0] = 0.0f;
                out.normal[1] = 1.0f;
                out.normal[2] = 0.0f;
                out.materialIdx = tri.materialIdx; // preserve 0x80000000 marker
                out.pad0 = 0.0f;
                out.pad1 = 0.0f;
                out.pad2 = 0.0f;
            } else {
                // Real triangle: pack v0/v1/v2 + face normal.
                out.v0[0] = tri.v0[0];
                out.v0[1] = tri.v0[1];
                out.v0[2] = tri.v0[2];
                out.v1[0] = tri.v1[0];
                out.v1[1] = tri.v1[1];
                out.v1[2] = tri.v1[2];
                out.v2[0] = tri.v2[0];
                out.v2[1] = tri.v2[1];
                out.v2[2] = tri.v2[2];
                // Face normal = normalize(cross(v1-v0, v2-v0)).
                const float e1x = tri.v1[0] - tri.v0[0];
                const float e1y = tri.v1[1] - tri.v0[1];
                const float e1z = tri.v1[2] - tri.v0[2];
                const float e2x = tri.v2[0] - tri.v0[0];
                const float e2y = tri.v2[1] - tri.v0[1];
                const float e2z = tri.v2[2] - tri.v0[2];
                float nx = e1y * e2z - e1z * e2y;
                float ny = e1z * e2x - e1x * e2z;
                float nz = e1x * e2y - e1y * e2x;
                const float nlen = std::sqrt(nx * nx + ny * ny + nz * nz);
                const float invNlen = nlen > 1e-12f ? 1.0f / nlen : 0.0f;
                out.normal[0] = nx * invNlen;
                out.normal[1] = ny * invNlen;
                out.normal[2] = nz * invNlen;
                out.materialIdx = tri.materialIdx;
                out.pad0 = 0.0f;
                out.pad1 = 0.0f;
                out.pad2 = 0.0f;
            }
            out.uv0[0] = tri.uv0[0];
            out.uv0[1] = tri.uv0[1];
            out.uv1[0] = tri.uv1[0];
            out.uv1[1] = tri.uv1[1];
            out.uv2[0] = tri.uv2[0];
            out.uv2[1] = tri.uv2[1];
        }
        const bool forceFullLeafUpload = !result.refitted || leafBufferRecreated;
        const auto leafDiff = arp::core::buildContiguousDiffRanges(gpuLeaves.data(),
            gpuLeaves.size(),
            forceFullLeafUpload || cachedGpuBvhLeaves_.empty() ? nullptr
                                                               : cachedGpuBvhLeaves_.data(),
            forceFullLeafUpload ? 0u : cachedGpuBvhLeaves_.size(),
            kMaximumBvhUploadRanges,
            bvhUploadRanges_);
        result.changedLeafCount = static_cast<std::uint32_t>(leafDiff.changedElementCount);
        result.fullUpload = result.fullUpload || leafDiff.fullRangeFallback;
        if (leafDiff.changedElementCount != 0u && !bvhUploadRanges_.empty()) {
            const auto changedLeafIndex = bvhUploadRanges_.front().firstElement;
            const auto triangleIndex = leaves[changedLeafIndex].handle;
            result.firstChangedPrimitiveId = input.triangles[triangleIndex].stableId;
        }
        for (const auto& range : bvhUploadRanges_) {
            const auto sizeBytes = range.elementCount * sizeof(GpuBvhLeafData);
            const auto offsetBytes = range.firstElement * sizeof(GpuBvhLeafData);
            const auto leavesWritten = device_.writeBuffer(*sceneBvhLeavesBuffer_,
                gpuLeaves.data() + range.firstElement,
                sizeBytes,
                offsetBytes);
            if (!leavesWritten.success) {
                return {false, "DDGI-BVH-LEAF-UPLOAD-FAILED: " + leavesWritten.diagnostics};
            }
            result.uploadBytes += sizeBytes;
            ++result.uploadRangeCount;
        }

        const auto emissiveDiff = arp::core::buildContiguousDiffRanges(gpuEmissive.data(),
            gpuEmissive.size(),
            forceFullLeafUpload || cachedGpuBvhEmissive_.empty() ? nullptr
                                                                 : cachedGpuBvhEmissive_.data(),
            forceFullLeafUpload ? 0u : cachedGpuBvhEmissive_.size(),
            kMaximumBvhUploadRanges,
            bvhUploadRanges_);
        result.changedLeafCount = std::max(
            result.changedLeafCount, static_cast<std::uint32_t>(emissiveDiff.changedElementCount));
        result.fullUpload = result.fullUpload || emissiveDiff.fullRangeFallback;
        for (const auto& range : bvhUploadRanges_) {
            const auto sizeBytes = range.elementCount * sizeof(GpuBvhEmissiveData);
            const auto offsetBytes = range.firstElement * sizeof(GpuBvhEmissiveData);
            const auto emissiveWritten = device_.writeBuffer(*sceneBvhEmissiveBuffer_,
                gpuEmissive.data() + range.firstElement,
                sizeBytes,
                offsetBytes);
            if (!emissiveWritten.success) {
                return {false, "DDGI-BVH-EMISSIVE-UPLOAD-FAILED: " + emissiveWritten.diagnostics};
            }
            result.uploadBytes += sizeBytes;
            ++result.uploadRangeCount;
        }

        if (recoverStorage) {
            const auto identityInstance = identityBvhInstance();
            const auto written = device_.writeBuffer(
                *sceneBvhInstanceBuffer_, &identityInstance, sizeof(identityInstance));
            if (!written.success)
                return {false, "DDGI-INSTANCE-TABLE-UPLOAD-FAILED: " + written.diagnostics};
            result.uploadBytes += sizeof(identityInstance);
            ++result.uploadRangeCount;
        }
        cachedGpuBvhNodes_.assign(serializedGpuNodes.begin(), serializedGpuNodes.end());
        cachedGpuBvhLeaves_.assign(gpuLeaves.begin(), gpuLeaves.end());
        cachedGpuBvhEmissive_.assign(gpuEmissive.begin(), gpuEmissive.end());

        result.triangleCount = static_cast<std::uint32_t>(leafCount);
        result.nodeCount = static_cast<std::uint32_t>(nodeCount);
        result.staticTriangleCount = result.triangleCount;
        result.staticNodeCount = result.nodeCount;
        result.instanceCount = 1u;
        result.proxyAabbCount = proxyCount;
        result.rebuilt = !result.refitted;
        result.uploadMilliseconds =
            std::chrono::duration<float, std::milli>(std::chrono::steady_clock::now() - uploadStart)
                .count();
        cachedSceneGeometryRevision_ = input.geometryRevision;
        sceneBvhUploadValid_ = true;
        sceneBvhStorageMode_ = SceneBvhStorageMode::Flat;
        cachedStaticGeometryRevision_ = staticRevision;
        cachedDynamicGeometryRevision_ = dynamicRevision;
        cachedStaticTransformRevision_ = staticTransformRevision;
        cachedSceneBvhResult_ = result;
        telemetry_.accelerationBuildMilliseconds = result.buildMilliseconds;
        telemetry_.accelerationRefitMilliseconds = result.refitMilliseconds;
        telemetry_.accelerationUploadMilliseconds = result.uploadMilliseconds;
        telemetry_.accelerationUploadBytes = result.uploadBytes;
        telemetry_.accelerationChangedNodeCount = result.changedNodeCount;
        telemetry_.accelerationChangedLeafCount = result.changedLeafCount;
        telemetry_.accelerationUploadRangeCount = result.uploadRangeCount;
        telemetry_.accelerationRebuilt = result.rebuilt;
        telemetry_.accelerationRefitted = result.refitted;
        telemetry_.accelerationReused = result.reused;
        return result;
    }

    const DdgiTelemetry& telemetry() const noexcept { return telemetry_; }

    void setGpuBudgetMilliseconds(float milliseconds) noexcept
    {
        if (std::isfinite(milliseconds) && milliseconds > 0.0f) {
            gpuBudgetMilliseconds_ = milliseconds;
        }
    }

    // FrameGraph exposes caller-owned opaque timing ids. The DDGI scheduler
    // must only use its own pass scopes; summing the whole-frame scope and
    // unrelated renderer scopes falsely throttles the probe budget to one.
    // Applications that register DDGI timing scopes should provide their ids;
    // when unset, scheduling stays at the configured probe budget.
    void setGpuTimingScopeIds(
        std::uint64_t relocate, std::uint64_t update, std::uint64_t resolve) noexcept
    {
        gpuTimingScopeIds_ = {relocate, update, resolve};
    }

    RendererResult setSkyEnvironment(const DdgiSkyEnvironmentDesc& environment)
    {
        if (!recordingReady_ || !skyEnvironmentUbo_) {
            return {false, "DDGI sky-environment UBO is not initialized"};
        }
        if (!isValidDdgiSkyEnvironment(environment)) {
            return {false, "DDGI-SKY-ENVIRONMENT-INVALID"};
        }
        const auto gpu = packDdgiSkyEnvironment(environment);
        if (skyEnvironmentUploadValid_
            && std::memcmp(&gpu, &cachedSkyEnvironment_, sizeof(gpu)) == 0)
            return {true, ""};
        if (!sharedInputsReady())
            return {false, "DDGI-SHARED-SKY-INPUT-NOT-READY"};
        invalidatePreparedInput();
        skyEnvironmentUploadValid_ = false;
        const auto written = device_.writeBuffer(*skyEnvironmentUbo_, &gpu, sizeof(gpu));
        if (!written.success) {
            return {false, "DDGI sky-environment UBO upload failed: " + written.diagnostics};
        }
        cachedSkyEnvironment_ = gpu;
        skyEnvironmentUploadValid_ = true;
        return {true, ""};
    }

    RendererResult setCsmShadow(const DdgiCsmShadowDesc& shadow)
    {
        if (!recordingReady_ || !csmShadowUbo_) {
            return {false, "DDGI CSM shadow UBO is not initialized"};
        }
        if (!isValidDdgiCsmShadow(shadow)) {
            return {false, "DDGI-CSM-SHADOW-INVALID"};
        }
        if (csmShadowUploadValid_ && std::memcmp(&shadow, &cachedCsmShadow_, sizeof(shadow)) == 0)
            return {true, ""};
        if (!sharedInputsReady())
            return {false, "DDGI-SHARED-CSM-INPUT-NOT-READY"};
        invalidatePreparedInput();
        csmShadowUploadValid_ = false;
        const auto written = device_.writeBuffer(*csmShadowUbo_, &shadow, sizeof(shadow));
        if (!written.success) {
            return {false, "DDGI CSM shadow UBO upload failed: " + written.diagnostics};
        }
        cachedCsmShadow_ = shadow;
        csmShadowUploadValid_ = true;
        return {true, ""};
    }

