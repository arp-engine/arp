"""Reproducible tool evidence for frozen WebGL1 products, separate from RHI admission."""
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
from uuid import uuid4

import yaml

from emscripten_preload_package import EmscriptenPreloadPackage
from webgl1_runtime_build import WebGl1RuntimeBuilder


class WebGlVisualValidation:
    bundle_names = ('pipeline.html', 'arp_webgl1_runtime_validation.js',
                    'arp_webgl1_runtime_validation.wasm', 'arp_webgl1_runtime_validation.data')
    profiles = ('scene2d', 'gui', 'basic-forward')
    program_names = {'scene2d': ('scene_2d_vertices',), 'gui': ('gui_bitmap',),
                     'basic-forward': ('basic_forward', 'gui_bitmap', 'basic_depth_receiver')}

    def __init__(self, root, manifest, output, qrenderdoc, browser=None, bundle=None,
                 replay_source=None, profiles=None):
        self.root = Path(root).resolve()
        self.manifest = Path(manifest).resolve()
        self.bundle = Path(bundle).resolve() if bundle else self.manifest.parent
        self.output = Path(output).resolve()
        self.qrenderdoc = Path(qrenderdoc).resolve()
        self.browser = Path(browser).resolve() if browser else None
        self.replay_source = Path(replay_source).resolve() if replay_source else None
        self.selected = tuple(profiles or self.profiles)
        self.report = None

    @staticmethod
    def hashes(directory):
        return {n: WebGl1RuntimeBuilder.sha(Path(directory)/n) for n in WebGlVisualValidation.bundle_names}

    def validate(self):
        if not self.selected or len(set(self.selected)) != len(self.selected) or any(
                p not in self.profiles for p in self.selected):
            raise ValueError('WEBGL-VISUAL-PROFILES')
        if not self.qrenderdoc.is_file() or (not self.replay_source and (
                not self.browser or not self.browser.is_file())):
            raise ValueError('WEBGL-VISUAL-TOOL-MISSING')
        # Append-only evidence must never create files inside a source/input cohort.
        for protected in (self.bundle, self.manifest.parent, self.replay_source):
            if protected and (self.output == protected or protected in self.output.parents):
                raise ValueError('WEBGL-VISUAL-OUTPUT-INPUT')
        if self.output == self.root or any(self.output == self.root/n or self.root/n in self.output.parents
                for n in ('src', 'scripts', 'tests', 'cmake', 'docs', '3rd', 'generated', 'shaders', '.git')):
            raise ValueError('WEBGL-VISUAL-OUTPUT-SOURCE')
        document = yaml.safe_load(self.manifest.read_text(encoding='utf8'))
        if (document.get('type') != 'WebGl1RuntimeComponentBuild' or document.get('contractVersion') != 1
                or document.get('status') != 'Prototype Complete'
                or document.get('allNamedInputsMatch') is not True
                or document.get('sourceInputs') != document.get('sourceInputsAfter')
                or not document.get('sourceInputs') or not document.get('steps')
                or any(s.get('exitCode') != 0 for s in document['steps'])
                or document.get('productionReady') is not False
                or document.get('gpuCompletionClaimed') is not False):
            raise ValueError('WEBGL-VISUAL-BUILD-INCOMPLETE')
        actual = self.hashes(self.bundle)
        for name in self.bundle_names:
            # HTML is generated by the original root but older manifests list only runtime.*.
            expected = (document.get('artifacts', {}).get(name) if name != 'pipeline.html' else
                        WebGl1RuntimeBuilder.sha(self.manifest.parent/name))
            if not expected or actual[name] != expected:
                raise ValueError('WEBGL-VISUAL-BUNDLE-IDENTITY: '+name)
        scripts = re.findall(r'<script src="([^"]+\.js)"></script>',
                             (self.bundle/'pipeline.html').read_text(encoding='utf8'))
        if scripts != ['arp_webgl1_runtime_validation.js']:
            raise ValueError('WEBGL-VISUAL-ENTRY-IDENTITY')
        if self.replay_source:
            custody = yaml.safe_load((self.replay_source/'bundle-hashes.yaml').read_text(encoding='utf8'))
            original = Path(custody['rootManifest'])
            if not original.is_absolute():
                original = self.root/original
            if (original.resolve() != self.manifest or custody.get('allNamedInputsMatch') is not True
                    or custody.get('files') != actual or self.hashes(self.replay_source/'bundle') != actual):
                raise ValueError('WEBGL-VISUAL-REPLAY-COHORT')
        return document, actual

    def programs(self, bundle):
        """Retain original publication identities, not equality with ANGLE-compiled DXBC."""
        package = EmscriptenPreloadPackage(bundle/'arp_webgl1_runtime_validation.js')
        result = {}
        for name in sorted({n for p in self.selected for n in self.program_names[p]}):
            key = '/artifacts/'+name+'.webgl-program.yaml'
            raw = package.read(key)
            publication = yaml.safe_load(raw)
            if (publication.get('type') != 'WebGlShaderProgramArtifact'
                    or publication.get('contractVersion') != 1
                    or publication.get('profile') != 'WebGl1Graphics/1'
                    or len(publication.get('targets', [])) != 2):
                raise ValueError('WEBGL-VISUAL-PROGRAM-CONTRACT: '+key)
            targets = {}
            for target in publication['targets']:
                path = '/artifacts/'+target['path']
                # EmscriptenPreloadPackage validates canonical paths and bounded source ranges.
                contents = package.read(path)
                digest = hashlib.sha256(contents).hexdigest()
                if digest != target['sha256']:
                    raise ValueError('WEBGL-VISUAL-PROGRAM-HASH: '+path)
                targets[path] = digest
            result[key] = dict(sha256=hashlib.sha256(raw).hexdigest(), targets=targets,
                               textureUnits=publication.get('textureUnits', []),
                               nativeByteEqualityClaimed=False)
        return result

    def tools(self):
        names = [self.qrenderdoc, Path(sys.executable), self.manifest]
        if self.browser:
            names.append(self.browser)
        # Includes transitive first-party Python helpers. These may differ from build-time tools.
        names += list((self.root/'scripts').glob('*.py')) + list((self.root/'tests/tools').glob('*.py'))
        return {str(p): WebGl1RuntimeBuilder.sha(p) for p in sorted(set(names))}

    @staticmethod
    def validate_replay(report, profile):
        sys.path.insert(0, str(Path(__file__).resolve().parents[1]/'tests/tools'))
        from webgl_product_native_state import WebGlProductNativeState
        if (report.get('success') is not True or report.get('productionReady') is not False
                or report.get('gpuCompletionClaimed') is not False or not report.get('frames')):
            raise ValueError('WEBGL-VISUAL-REPLAY-FAILED')
        frames = report['frames']
        if any(f.get('replayErrors') != [] for f in frames):
            raise ValueError('WEBGL-VISUAL-REPLAY-ERRORS')
        draws = [d for f in frames for d in f['draws']]
        if (not draws or report.get('verifiedDraws') != len(draws)
                or {tuple(d['extent']) for d in draws} != {(64, 64), (48, 32)}
                or any(not d.get('nativeState') or d.get('verifiedOutputPixels', 0) <= 0
                       or not d.get('outputTarget') or len(d.get('outputSha256', '')) != 64
                       or d.get('verifiedPostVsVertices') != 6 for d in draws)):
            raise ValueError('WEBGL-VISUAL-REPLAY-COVERAGE')
        ordinal_key = {'scene2d': 'batch', 'gui': 'command', 'basic-forward': 'ordinal'}[profile]
        for draw in draws:
            WebGlProductNativeState.validate(draw['nativeState'], profile, draw[ordinal_key], draw['extent'])
        return dict(captures=len(frames), verifiedDraws=len(draws),
                    outputPixels=sum(d['verifiedOutputPixels'] for d in draws),
                    postVsVertices=sum(d.get('verifiedPostVsVertices', 0) for d in draws), replayErrors=[])

    def run(self):
        build, before = self.validate()
        self.output.mkdir(parents=True, exist_ok=True)
        directory = self.output/(datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'-'+uuid4().hex[:8])
        directory.mkdir(exist_ok=False)
        self.report = directory/'visual-manifest.yaml'
        document = dict(type='WebGlProductVisualValidation', contractVersion=1, success=False,
            status='Running', evidenceKind='ToolNativeReplay', buildManifest=str(self.manifest),
            buildType=build.get('buildType'), buildInputsVerifiedAtBuild=True,
            gpuCompletionClaimed=False, productionReady=False, readinessPromoted=False,
            sealedRhiAdmission=False, platformValidated=False, bundleHashes=before,
            toolInputs=self.tools(), programs={}, steps=[], profiles={})

        def save():
            self.report.write_text(yaml.safe_dump(document, sort_keys=False), encoding='utf8')

        def execute(name, command, env=None):
            command = [str(p) for p in command]
            with (directory/(name+'.log')).open('w', encoding='utf8') as log:
                completed = subprocess.run(command, cwd=self.root, env=env, stdout=log,
                                           stderr=subprocess.STDOUT, timeout=300)
            document['steps'].append(dict(name=name, command=command, exitCode=completed.returncode))
            save()
            if completed.returncode:
                raise RuntimeError('WEBGL-VISUAL-STEP-FAILED: '+name)

        save()
        try:
            bundle = directory/'bundle'
            bundle.mkdir()
            for name in self.bundle_names:
                shutil.copy2(self.bundle/name, bundle/name)
            if self.hashes(bundle) != before:
                raise ValueError('WEBGL-VISUAL-FREEZE-DRIFT')
            shutil.copy2(self.manifest, directory/'original-build-manifest.yaml')
            document['programs'] = self.programs(bundle)
            sys.path.insert(0, str(self.root/'tests/tools'))
            from run_webgl_shader_capture import snapshot_product_inputs
            for profile in self.selected:
                target = directory/profile
                target.mkdir()
                source_hashes = {}
                if self.replay_source:
                    source = self.replay_source/profile
                    paths = [source/'runtime.json', source/('scene2d-inputs.json' if profile == 'scene2d' else 'gui-inputs.json')]
                    captures = sorted(source.glob('program_frame*.rdc'))
                    if not captures:
                        raise ValueError('WEBGL-VISUAL-NO-CAPTURES')
                    # Reconstruct input pixels from the exact preload, then compare the old snapshot.
                    snapshot_product_inputs(bundle, 'pipeline.html', target, profile != 'scene2d')
                    if paths[1].read_bytes() != (target/paths[1].name).read_bytes():
                        raise ValueError('WEBGL-VISUAL-ORIGINAL-INPUTS')
                    for path in paths[:1]+captures:
                        source_hashes[str(path)] = WebGl1RuntimeBuilder.sha(path)
                        shutil.copy2(path, target/path.name)
                        if WebGl1RuntimeBuilder.sha(target/path.name) != source_hashes[str(path)]:
                            raise ValueError('WEBGL-VISUAL-CAPTURE-COPY')
                    document['profiles'][profile] = dict(replaySource=str(source), sourceHashes=source_hashes)
                else:
                    execute(profile+'-capture', [sys.executable, '-X', 'utf8',
                        self.root/'tests/tools/run_webgl_shader_capture.py', '--directory', bundle,
                        '--output', target, '--browser', self.browser, '--qrenderdoc', self.qrenderdoc,
                        '--entry', 'pipeline.html', '--capture-frames', '24', '--'+profile+'-only'])
                    document['profiles'][profile] = dict(freshCapture=True)
                runtime = json.loads((target/'runtime.json').read_text(encoding='utf8'))
                environment = runtime.get('runtimeEnvironment', {})
                if (runtime.get('success') is not True or environment.get('contextAttributes', {}).get('alpha') is not False
                        or not environment.get('version', '').startswith('WebGL 1.0')):
                    raise ValueError('WEBGL-VISUAL-CONTEXT-IDENTITY')
                document['profiles'][profile]['runtimeEnvironment'] = environment
                env = dict(os.environ, ARP_REPO_ROOT=str(self.root), ARP_WEBGL_PROGRAM_CAPTURE=str(target))
                execute(profile+'-replay', [self.qrenderdoc, '--python',
                        self.root/('tests/tools/analyze_webgl_'+profile.replace('-', '_')+'.py')], env)
                replay = json.loads((target/'replay.json').read_text(encoding='utf8'))
                captures = {str(p) for p in target.glob('program_frame*.rdc')}
                if {f['capture'] for f in replay.get('frames', [])} != captures:
                    raise ValueError('WEBGL-VISUAL-REPLAY-CAPTURE-COVERAGE')
                document['profiles'][profile]['summary'] = self.validate_replay(replay, profile)
                if source_hashes != {p: WebGl1RuntimeBuilder.sha(p) for p in source_hashes}:
                    raise ValueError('WEBGL-VISUAL-CAPTURE-DRIFT')
                document['profiles'][profile]['evidenceFiles'] = {
                    str(p.relative_to(directory)): WebGl1RuntimeBuilder.sha(p)
                    for p in sorted(target.iterdir()) if p.suffix in ('.json', '.rdc', '.bmp')}
                save()
            if self.tools() != document['toolInputs'] or self.hashes(self.bundle) != before or self.hashes(bundle) != before:
                raise ValueError('WEBGL-VISUAL-INPUT-DRIFT')
            document.update(success=True, status='Backend Validated', validationScope='WebGL1/ANGLE/D3D11 product replay')
        except Exception as error:
            document.update(status='Failed', diagnostic=str(error))
            raise
        finally:
            save()
        return self.report
